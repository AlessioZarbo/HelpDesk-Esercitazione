namespace HelpDesk.Domain.Enums;

/// <summary>
/// Represents the priority levels for support tickets in the HelpDesk system.
/// </summary>
public enum Priority {

	/// <summary>
	/// Indicates a low priority ticket.
	/// </summary>
	Low = 1,

	/// <summary>
	/// Indicates a normal priority ticket.
	/// </summary>
	Medium = 2,

	/// <summary>
	/// Indicates a high priority ticket.
	/// </summary>
	High = 3,

	/// <summary>
	/// Indicates a critical priority ticket.
	/// </summary>
	Critical = 4
}
